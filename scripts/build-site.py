#!/usr/bin/env python3
"""Build the announcements pages of the sc-agent site.

Derived pages are build artifacts: pages.yml runs this at deploy time, so the
deployed site cannot disagree with the committed markdown. Never commit
site/announcements/index.html or site/announcements/*.html.

Sources: site/announcements/*.md, whose first line is
    # <release> — <subtitle>
and which carry a "**Released:** Month D, YYYY" line (or "pending").

Ordering: sc-agent releases are versioned, so newest = highest version, not the
newest date — a release prepared ahead of publication (v0.4.1) belongs at the
top while its date is still "pending".

Usage: python3 scripts/build-site.py
"""
from __future__ import annotations

import html
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
ANN = SITE / "announcements"

TITLE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)
VERSION = re.compile(r"v?(\d+)\.(\d+)\.(\d+)")
RELEASED = re.compile(r"\*\*Released:\*\*\s*([A-Z][a-z]+ \d{1,2}, \d{4})")
BANNER = "<!-- generated by scripts/build-site.py — do not edit -->"

STYLE = """    body { font-family: -apple-system, system-ui, sans-serif; max-width: 52rem;
           margin: 3rem auto; padding: 0 1.5rem; line-height: 1.6; color: #1a1a2e; }
    nav a { margin-right: 1rem; }
    h1 { font-size: 1.5rem; line-height: 1.3; }
    h2 { font-size: 1.1rem; margin-top: 2rem; }
    code { background: #f0f0f4; padding: 0.1rem 0.35rem; border-radius: 3px; }
    blockquote { border-left: 3px solid #ddd; margin: 1rem 0; padding-left: 1rem; color: #555; }
    footer { margin-top: 3rem; padding-top: 1rem; border-top: 1px solid #e6e6ea;
             color: #6b6b74; font-size: .85rem; }"""


def page(title: str, body: str) -> str:
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{html.escape(title)} · sc-agent</title>
{BANNER}
  <style>
{STYLE}
  </style>
</head>
<body>
{body}
</body>
</html>
"""


def inline(text: str) -> str:
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<em>\1</em>", text)
    text = re.sub(r"`(.+?)`", r"<code>\1</code>", text)
    text = re.sub(r"\[(.+?)\]\((.+?)\)", r'<a href="\2">\1</a>', text)
    return text


def render(md: pathlib.Path) -> tuple[str, str, tuple[int, ...]]:
    text = md.read_text(encoding="utf-8")
    heading = TITLE.search(text)
    full = heading.group(1).strip() if heading else md.stem
    release, _, subtitle = full.partition(" — ")
    version = VERSION.search(md.stem)
    order = tuple(int(x) for x in version.groups()) if version else (0, 0, 0)

    out: list[str] = ['  <nav><a href="../">&#8592; sc-agent home</a>'
                      '<a href="./">All announcements</a></nav>']
    in_list = False
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line.strip():
            if in_list:
                out.append("    </ul>")
                in_list = False
            continue
        if line.startswith("# "):
            out.append(f"    <h1>{inline(html.escape(line[2:]))}</h1>")
        elif line.startswith("## "):
            out.append(f"    <h2>{inline(html.escape(line[3:]))}</h2>")
        elif line.startswith(("- ", "* ")):
            if not in_list:
                out.append("    <ul>")
                in_list = True
            out.append(f"      <li>{inline(html.escape(line[2:]))}</li>")
        elif line.startswith(">"):
            out.append(f"    <blockquote>{inline(html.escape(line.lstrip('> ')))}</blockquote>")
        else:
            out.append(f"    <p>{inline(html.escape(line))}</p>")
    if in_list:
        out.append("    </ul>")
    out.append('    <footer>Announcements are historical and are not updated after publication.</footer>')
    md.with_suffix(".html").write_text(page(release or md.stem, "\n".join(out)), encoding="utf-8")
    return release, subtitle.strip(), order


def main() -> None:
    ANN.mkdir(parents=True, exist_ok=True)
    (SITE / ".nojekyll").touch()

    rows = []
    for md in sorted(ANN.glob("*.md")):
        release, subtitle, order = render(md)
        rows.append((order, md, release, subtitle))
    rows.sort(key=lambda r: r[0], reverse=True)

    items = "\n".join(
        f'    <li><a href="{html.escape(md.stem)}.html">{html.escape(release)}</a>'
        + (f" — {inline(html.escape(subtitle))}" if subtitle else "")
        + "</li>"
        for _order, md, release, subtitle in rows
    )
    body = f"""  <nav><a href="../">&#8592; sc-agent home</a></nav>
  <h1>Announcements</h1>
  <p>Press releases and release announcements for sc-agent. Announcements are
  historical and are not updated after publication.</p>
  <ul>
{items}
  </ul>
  <footer>Generated from <code>site/announcements/*.md</code>.</footer>"""
    (ANN / "index.html").write_text(page("Announcements", body), encoding="utf-8")
    print(f"OK: {len(rows)} announcement(s)")


if __name__ == "__main__":
    main()
