"""Wheel-shipped consumer, rendered by sc-compose and exercised over real loopback I/O."""
import importlib.resources
import importlib.util
import json
import pathlib
import subprocess
import threading
import tomllib

import pytest
import sc_agent

REQUEST = json.dumps({"model": "jev-latest", "state": "s", "questions": {"q": {"type": "noul"}}})
ROOT = pathlib.Path(__file__).resolve().parents[3]


def render_consumer(tmp_path, *, general_log=True, models=None, sitr=False):
    template = pathlib.Path(str(importlib.resources.files(sc_agent) / "templates/consumer.py.j2"))
    values = {"general_log": general_log, "models": models or ["dec"], "sitr": sitr}
    variables = tmp_path / "consumer-vars.json"
    variables.write_text(json.dumps(values))
    output = tmp_path / "consumer.py"
    subprocess.run(["sc-compose", "render", "--root", str(template.parent), "--file", str(template),
                    "--var-file", str(variables), "--strict", "--output", str(output)],
                   check=True, capture_output=True, text=True, timeout=60)
    spec = importlib.util.spec_from_file_location("rendered_consumer", output)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture
def consumer(tmp_path):
    return render_consumer(tmp_path)


def test_template_floor_and_versions_match_workspace():
    template = (importlib.resources.files(sc_agent) / "templates/consumer.py.j2").read_text()
    floors = tomllib.loads((ROOT / "floors.toml").read_text())
    version = tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]["package"]["version"]
    assert f'Python >={floors["python"]["floor"]}' in template
    assert f'minimum_version: "{floors["tools"]["sc-compose"]}"' in template
    assert f"Generated by sc-decidr {version}" in template
    assert (importlib.resources.files(sc_agent) / "__init__.pyi").is_file()


@pytest.mark.mode("ok")
@pytest.mark.parametrize("general_log", [False, True])
@pytest.mark.parametrize("models", [["dec"], ["dec", "jev", "haiku", "luna"]])
def test_rendered_feature_combinations_run_loopback(env, args, tmp_path, monkeypatch, general_log, models):
    client = render_consumer(tmp_path, general_log=general_log, models=models)
    assert client.MODELS == models
    records, passed = [], []
    send = sc_agent.send

    def observed(*positional, **kwargs):
        passed.append(kwargs)
        return send(*positional, **kwargs)

    monkeypatch.setattr(sc_agent, "send", observed)
    cancel = sc_agent.CancelToken()
    line, code = client.call(REQUEST, **args, abort_on=frozenset(), category_codes={},
                             cancel=cancel, general_log=records.append, timeout_secs=10)
    assert "response" in json.loads(line) and code is None
    assert passed[0]["model"] == "dec"
    assert ("general_log" in passed[0]) is general_log
    assert "provider" not in passed[0] and "session_log" not in passed[0]
    assert passed[0]["cancel"] is cancel
    assert bool(records) is general_log
    rows = [json.loads(line) for p in env[1].rglob("sessions.jsonl") for line in p.read_text().splitlines()]
    assert len(rows) == 1
    assert rows[0]["fields"]["project"] == args["project"]
    assert rows[0]["fields"]["agent_role"] == args["agent_role"]


@pytest.mark.mode("ordered")
@pytest.mark.parametrize("status,abort_on,cancelled", [
    (401, frozenset(), False), (401, frozenset({"auth"}), True),
    (401, frozenset({"auth", "quota"}), True), (402, frozenset({"auth", "quota"}), True),
])
def test_rendered_batch_aborts_only_selected_categories(env, args, consumer, status, abort_on, cancelled):
    cancel = sc_agent.CancelToken()
    loopback = env[0]
    results, errors, callbacks = [], [], []
    requests = [json.dumps({"model": "jev-latest", "state": str(i), "questions": {"q": {"type": "noul"}}}) for i in range(2)]

    def callback(line):
        if json.loads(line)["position"] == 0:
            callbacks.append(cancel.is_cancelled())
            loopback.ordered_release[1].set()

    def run():
        try:
            results.extend(consumer.call_batch(requests, **args, abort_on=abort_on,
                           category_codes={"auth": "AUTH", "quota": "QUOTA"},
                           cancel=cancel, workers=2, on_result=callback))
        except BaseException as error:
            errors.append(error)

    thread = threading.Thread(target=run)
    thread.start()
    try:
        for event in loopback.ordered_started[:2]:
            assert event.wait(60), "request did not enter loopback"
        loopback.ordered_release[0].set()
        thread.join(60)
    finally:
        for event in loopback.ordered_release:
            event.set()
        thread.join(60)
    assert not thread.is_alive() and not errors
    assert len(results) == 2 and len(loopback.requests) == 2
    assert results[0][1] == ("AUTH" if status == 401 else "QUOTA")
    assert callbacks == [cancelled]
    assert cancel.is_cancelled() is cancelled
    assert json.loads(results[1][0])["error"]["category"] == ("cancelled" if cancelled else ("auth" if status == 401 else "quota"))


def test_rendered_command_error_and_keyboard_interrupt_cancel(env, args, consumer, monkeypatch):
    cancel = sc_agent.CancelToken()
    with pytest.raises(sc_agent.SagError):
        consumer.call(REQUEST, **{**args, "model": "haiku"}, keyring_service="consumer",
                      abort_on=frozenset(), category_codes={}, cancel=cancel)
    assert not cancel.is_cancelled()
    assert env[0].requests == []

    def interrupted(*args, **kwargs):
        raise KeyboardInterrupt

    monkeypatch.setattr(sc_agent, "send", interrupted)
    with pytest.raises(KeyboardInterrupt):
        consumer.call(REQUEST, **args, abort_on=frozenset(), category_codes={}, cancel=cancel)
    assert cancel.is_cancelled()
