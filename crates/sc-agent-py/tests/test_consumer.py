    assert client.MODELS == models
    assert hasattr(client, "extract") is sitr
    records, passed = [], []
    send = sc_agent.send

    def observed(*positional, **kwargs):
        passed.append(kwargs)
        return send(*positional, **kwargs)

    monkeypatch.setattr(sc_agent, "send", observed)
