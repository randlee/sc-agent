@pytest.mark.mode("ordered")
@pytest.mark.parametrize("status,abort_on,cancelled", [
    (401, frozenset(), False), (401, frozenset({"auth"}), True),
    (401, frozenset({"auth", "quota"}), True), (402, frozenset({"auth", "quota"}), True),
])
def test_rendered_batch_aborts_only_selected_categories(env, args, consumer, status, abort_on, cancelled):
    cancel = sc_agent.CancelToken()
    loopback = env[0]
    results, errors, callbacks = [], [], []
    requests = [json.dumps({"model": "jev-latest", "state": str(i), "questions": {"q": {"type": "noul"}}}) for i in range(2)]

    def callback(record):
        if record["position"] == 0:
            callbacks.append(cancel.is_cancelled())
            loopback.ordered_release[1].set()

    def run():
        try:
            result = consumer.call_batch_results(requests, **{k: v for k, v in args.items() if k != "agent_role"}, abort_on=abort_on,
                           category_codes={"auth": "AUTH", "quota": "QUOTA"},
                           cancel=cancel, workers=2, on_result=callback)
            assert result["ok"]
            results.extend(result["value"])
        except BaseException as error:
            errors.append(error)

    thread = threading.Thread(target=run)
    thread.start()
    try:
        for event in loopback.ordered_started[:2]:
            assert event.wait(60), "request did not enter loopback"
        loopback.ordered_release[0].set()
        thread.join(60)
    finally:
        for event in loopback.ordered_release:
            event.set()
        thread.join(60)
    assert not thread.is_alive() and not errors
    assert len(results) == 2 and len(loopback.requests) == 2
    assert results[0]["error"].code == ("AUTH" if status == 401 else "QUOTA")
    assert callbacks == [cancelled]
    assert cancel.is_cancelled() is cancelled
    assert results[1]["error"].data["category"] == ("cancelled" if cancelled else ("auth" if status == 401 else "quota"))


